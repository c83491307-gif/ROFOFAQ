package com.creazzy.rofof.feature.awareness

import android.Manifest
import android.annotation.SuppressLint
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import android.os.Build
import androidx.core.app.NotificationCompat
import androidx.core.app.NotificationManagerCompat
import androidx.core.content.ContextCompat
import com.creazzy.rofof.app.MainActivity

/** Posts rule-driven notifications only after Android has granted notification access. */
class NotificationHelper(context: Context) {
    private val appContext = context.applicationContext
    private val manager = NotificationManagerCompat.from(appContext)
    private val preferences = appContext.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE)

    fun showBudgetRule(
        stateKey: String,
        band: Int,
        title: String,
        message: String,
        language: String
    ) {
        if (band !in 1..2 || !canNotify()) return
        val previousBand = preferences.getInt(stateKey, 0)
        if (band <= previousBand) return

        ensureChannel()
        val intent = Intent(appContext, MainActivity::class.java).apply {
            action = MainActivity.ACTION_OPEN_DASHBOARD
            flags = Intent.FLAG_ACTIVITY_CLEAR_TOP or Intent.FLAG_ACTIVITY_SINGLE_TOP
        }
        val pendingIntent = PendingIntent.getActivity(
            appContext,
            stateKey.hashCode(),
            intent,
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
        )
        val notification = NotificationCompat.Builder(appContext, CHANNEL_ID)
            .setSmallIcon(android.R.drawable.ic_dialog_info)
            .setContentTitle(title)
            .setContentText(message)
            .setStyle(NotificationCompat.BigTextStyle().bigText(message))
            .setContentIntent(pendingIntent)
            .setAutoCancel(true)
            .setOnlyAlertOnce(true)
            .setPriority(NotificationCompat.PRIORITY_HIGH)
            .build()

        runCatching {
            postNotification(stateKey, stateKey.hashCode(), notification)
            preferences.edit().putInt(stateKey, band).apply()
        }
    }

    fun resetBudgetRule(stateKey: String) {
        preferences.edit().remove(stateKey).apply()
    }

    private fun canNotify(): Boolean {
        if (Build.VERSION.SDK_INT >= 33 &&
            ContextCompat.checkSelfPermission(appContext, Manifest.permission.POST_NOTIFICATIONS) !=
            PackageManager.PERMISSION_GRANTED
        ) return false
        return manager.areNotificationsEnabled()
    }

    /**
     * The caller must pass the canNotify() guard before reaching this method.
     * Keep the lint suppression local to the guarded platform call.
     */
    @SuppressLint("MissingPermission")
    private fun postNotification(tag: String, id: Int, notification: android.app.Notification) {
        manager.notify(tag, id, notification)
    }

    private fun ensureChannel() {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
        val platformManager = appContext.getSystemService(NotificationManager::class.java) ?: return
        if (platformManager.getNotificationChannel(CHANNEL_ID) != null) return
        platformManager.createNotificationChannel(
            NotificationChannel(
                CHANNEL_ID,
                "ROFOF · تنبيهات الميزانية",
                NotificationManager.IMPORTANCE_HIGH
            ).apply {
                description = "Local alerts generated by ROFOF budget rules"
            }
        )
    }

    companion object {
        private const val CHANNEL_ID = "rofof_rule_budget_alerts"
        private const val PREFERENCES = "rofof_rule_notification_state"
    }
}
